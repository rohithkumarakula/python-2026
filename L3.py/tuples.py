#tuples in python
# a built in data type that lets us create immutable sequences of values
# list - mutable, strings and tuples - immutable
# we can not add or delete elements in tuples


tuple = (2,1,3,1)
print(type(tuple))
print(tuple[0])
print(tuple[0:])


tup1 = (1,)  #if there is only 1 element in tuple add coma after it otherwise python treats its as integer
print(type(tup1))
print(tup1)

tup1 = (1)
print(type(tup1))
print(tup1)