#tuple methods
#------------------------------tup.index(el)--------------
#returns index of first occurence
tup = (1,2,3,4)
print(tup.index(3))  #prints index of 3 which is 2

#-----------------------------tup.count(el)----------------
#counts total occurences

tup = (1,2,3,4,2,2)
print(tup.count(2))  # there are total 3 2's
